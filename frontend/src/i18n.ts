export function formatPrice(n: number | undefined | null): string {
  const val = Math.round(Number(n || 0));
  return val.toString().replace(/\B(?=(\d{3})+(?!\d))/g, " ") + " so'm";
}

export function calcSellingPrice(
  yuan: number,
  weightKg: number,
  yuanRate: number,
  shippingPerKg: number,
  marginPct: number,
  manual?: number | null
): number {
  if (manual && manual > 0) return Math.round(manual);
  const raw = (yuan * yuanRate + weightKg * shippingPerKg) * (1 + marginPct / 100);
  return Math.floor((raw + 500) / 1000) * 1000;
}

const LangCtx = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (typeof TEXTS)["uz"];
}>({
  lang: "uz",
  setLang: () => { },
  t: TEXTS.uz,
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(
    () => ((localStorage.getItem("wm_lang") as Lang) || "uz")
  );
  const setLang = (l: Lang) => {
    localStorage.setItem("wm_lang", l);
    setLangState(l);
  };
  return React.createElement(
    LangCtx.Provider,
    { value: { lang, setLang, t: TEXTS[lang] } },
    children
  );
}

export function useLang() {
  return useContext(LangCtx);
}
